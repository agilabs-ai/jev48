#!/usr/bin/env python3
from __future__ import annotations

import argparse
from datetime import datetime, timezone
from pathlib import Path

from open_system_one.io import dump_json, file_sha256, read_jsonl


def main():
    p = argparse.ArgumentParser()
    p.add_argument("path")
    args = p.parse_args()
    path = Path(args.path)
    rows = read_jsonl(path)
    manifest = {
        "path": str(path),
        "sha256": file_sha256(path),
        "examples": len(rows),
        "domains": sorted(set(x.domain for x in rows)),
        "frozen_at_utc": datetime.now(timezone.utc).isoformat(),
        "policy": "Do not edit this file after querying Jev or any benchmark target. Create a new benchmark version instead.",
    }
    out = path.with_suffix(path.suffix + ".manifest.json")
    dump_json(out, manifest)
    print(manifest)


if __name__ == "__main__":
    main()
